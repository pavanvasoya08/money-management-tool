<?php

declare(strict_types=1);

namespace App\Services\Product;

use App\Core\App;
use App\Core\Database;
use App\Exceptions\HttpException;
use App\Services\Export\ReportFields;
use App\Support\BusinessDate;
use App\Support\Money;

/**
 * The ten product reports. Every report is limited to the products the user may see
 * (record scope) and applies the user's field rules on screen and in CSV / Excel / PDF.
 */
final class ProductReportService
{
    public const REPORTS = [
        'products' => ['Complete product list', 'Every product with type, category, brand, SKU, status, variants, suppliers and current GST/HSN.'],
        'categories' => ['Category-wise product report', 'Products per category (including sub-categories) by status.'],
        'brands' => ['Brand-wise product report', 'Products per brand by status.'],
        'variants' => ['Variant report', 'Every variant with its attributes, SKU, barcode, status and current prices.'],
        'pricing' => ['Product-wise pricing report', 'Prices in force on a date, per product, variant, price type and scope.'],
        'tax' => ['Product-wise GST / HSN report', 'GST/HSN configurations in force on a date.'],
        'no_suppliers' => ['Products without suppliers', 'Products that have no active supplier mapping.'],
        'no_tax' => ['Products without GST configuration', 'Products with no GST/HSN configuration in force today.'],
        'supplier_mappings' => ['Product-supplier mapping report', 'Which suppliers supply which products, with codes, quantities, lead time and purchase price.'],
        'inactive' => ['Inactive and archived products', 'Inactive, discontinued and archived products with the reason.'],
    ];

    public function __construct(private readonly Database $db)
    {
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $f @return array<string, mixed> */
    /** @var array{0: string, 1: list<mixed>} */
    private array $supplierScope = ['1 = 0', []];

    public function run(array $user, string $key, array $f): array
    {
        if (!isset(self::REPORTS[$key])) {
            throw new HttpException(404, 'Report not found.');
        }
        $scope = App::dataAccess()->constrain($user, 'products', 'p');
        // Supplier names follow the user's supplier scope (none without supplier access).
        $this->supplierScope = App::gate()->allows($user, 'suppliers.view') ? App::dataAccess()->constrain($user, 'suppliers', 's') : ['1 = 0', []];
        $date = BusinessDate::isValid((string) ($f['as_of'] ?? '')) ? (string) $f['as_of'] : BusinessDate::today();
        $out = match ($key) {
            'products' => $this->products($f, $scope, $date),
            'categories' => $this->groups($f, $scope, 'category'),
            'brands' => $this->groups($f, $scope, 'brand'),
            'variants' => $this->variants($f, $scope, $date),
            'pricing' => $this->pricing($f, $scope, $date),
            'tax' => $this->tax($f, $scope, $date),
            'no_suppliers' => $this->products(['missing' => 'supplier'] + $f, $scope, $date),
            'no_tax' => $this->products(['missing' => 'tax'] + $f, $scope, $date),
            'supplier_mappings' => $this->mappings($f, $scope, $date),
            'inactive' => $this->inactive($f, $scope),
        };
        $out += ['totals' => null, 'notice' => null];
        $out = ReportFields::apply($user, $out);
        $out['title'] = self::REPORTS[$key][0];
        $out['meta'] = [App::dataAccess()->resolve($user, 'products')->describe() . ' · generated by ' . $user['name'] . ' · ' . format_datetime(now())];
        if (in_array($key, ['pricing', 'tax', 'variants', 'supplier_mappings', 'products'], true)) {
            $out['meta'][] = 'Values in force on ' . BusinessDate::format($date);
        }
        return $out;
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function products(array $f, array $scope, string $date): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql($f, $scope);
        $catalog = new CatalogService($this->db);
        $rows = [];
        foreach ($this->db->select("SELECT p.*, t.name AS type_name, b.name AS brand_name,
                (SELECT COUNT(*) FROM product_variants v WHERE v.product_id = p.id AND v.status <> 'archived') AS variants,
                (SELECT COUNT(*) FROM product_supplier_mappings m WHERE m.product_id = p.id AND m.status = 'active') AS suppliers
            FROM products p JOIN product_types t ON t.id = p.product_type_id LEFT JOIN product_brands b ON b.id = p.brand_id WHERE {$w} ORDER BY p.name", $p) as $r) {
            $tax = (new TaxConfigService($this->db))->resolve((int) $r['id'], null, null, $date);
            $price = (new PricingService($this->db))->priceOn((int) $r['id'], null, 'standard_selling', $date);
            $rows[] = ['code' => $r['product_code'], 'name' => $r['name'], 'sku' => $r['sku'] ?? '', 'type' => $r['type_name'], 'category' => $catalog->categoryPath($r['subcategory_id'] !== null ? (int) $r['subcategory_id'] : ($r['category_id'] !== null ? (int) $r['category_id'] : null)),
                'brand' => $r['brand_name'] ?? '', 'unit' => $r['unit'], 'status' => ProductService::STATUSES[$r['status']] ?? $r['status'], 'variants' => (int) $r['variants'], 'suppliers' => (int) $r['suppliers'],
                'hsn' => $tax !== null ? (string) ($tax['hsn_code'] ?? $tax['sac_code'] ?? '') : '', 'gst_rate' => $tax !== null ? ($tax['rate_name'] ?? TaxConfigService::APPLICABILITY[$tax['applicability']]) : '',
                'selling_price' => $price !== null ? Money::fromDb($price['amount']) : null, 'barcode' => $r['barcode'] ?? '', 'uuid' => $r['uuid']];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Product'], 'sku' => ['label' => 'SKU'], 'type' => ['label' => 'Type'], 'category' => ['label' => 'Category'],
            'brand' => ['label' => 'Brand'], 'unit' => ['label' => 'Unit'], 'status' => ['label' => 'Status'], 'variants' => ['label' => 'Variants', 'type' => 'number'], 'suppliers' => ['label' => 'Suppliers', 'type' => 'number'],
            'hsn' => ['label' => 'HSN / SAC', 'field' => ['products', 'tax_configuration']], 'gst_rate' => ['label' => 'GST', 'field' => ['products', 'tax_configuration']],
            'selling_price' => ['label' => 'Std. selling (INR)', 'type' => 'money', 'field' => ['products', 'selling_price']], 'barcode' => ['label' => 'Barcode'], 'uuid' => ['label' => 'Stable ID']],
            'rows' => $rows, 'totals' => ['code' => 'Total (' . count($rows) . ')']];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function groups(array $f, array $scope, string $by): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql(['archived' => 'with'] + $f, $scope);
        $products = $this->db->select("SELECT p.id, p.status, p.category_id, p.subcategory_id, p.brand_id, (SELECT COUNT(*) FROM product_variants v WHERE v.product_id = p.id AND v.status <> 'archived') AS variants FROM products p WHERE {$w}", $p);
        $catalog = new CatalogService($this->db);
        $groups = [];
        if ($by === 'category') {
            foreach ($catalog->categoryTree(true) as $c) {
                $groups[(int) $c['id']] = ['name' => $c['path'], 'code' => $c['code'], 'state' => (int) $c['is_archived'] ? 'Archived' : ucfirst($c['status']), 'ids' => array_merge([(int) $c['id']], $catalog->descendantIds((int) $c['id']))];
            }
        } else {
            foreach ($catalog->brands(true) as $b) {
                $groups[(int) $b['id']] = ['name' => $b['name'], 'code' => $b['code'], 'state' => (int) $b['is_archived'] ? 'Archived' : ucfirst($b['status']), 'ids' => [(int) $b['id']]];
            }
        }
        $groups[0] = ['name' => $by === 'category' ? '(No category)' : '(No brand)', 'code' => '', 'state' => '', 'ids' => []];
        $rows = [];
        $totals = ['total' => 0, 'active' => 0, 'draft' => 0, 'inactive' => 0, 'archived' => 0, 'variants' => 0];
        foreach ($groups as $gid => $g) {
            $count = ['total' => 0, 'active' => 0, 'draft' => 0, 'inactive' => 0, 'archived' => 0, 'variants' => 0];
            foreach ($products as $pr) {
                $match = $by === 'category'
                    ? ($gid === 0 ? $pr['category_id'] === null : in_array((int) $pr['category_id'], $g['ids'], true) || in_array((int) $pr['subcategory_id'], $g['ids'], true))
                    : ($gid === 0 ? $pr['brand_id'] === null : (int) $pr['brand_id'] === $gid);
                if (!$match) {
                    continue;
                }
                $count['total']++;
                $bucket = match ($pr['status']) { 'active' => 'active', 'archived' => 'archived', 'inactive', 'discontinued' => 'inactive', default => 'draft' };
                $count[$bucket]++;
                $count['variants'] += (int) $pr['variants'];
            }
            if ($count['total'] === 0 && $gid === 0) {
                continue;
            }
            $rows[] = ['name' => $g['name'], 'code' => $g['code'], 'state' => $g['state']] + $count;
            if ($by === 'brand' || $gid === 0 || (int) ($this->db->scalar('SELECT parent_id FROM product_categories WHERE id = ?', [$gid]) ?? 0) === 0) {
                foreach ($count as $k => $v) {
                    $totals[$k] += $v; // top-level categories only, so sub-categories are not counted twice
                }
            }
        }
        $label = $by === 'category' ? 'Category' : 'Brand';
        return ['columns' => ['name' => ['label' => $label], 'code' => ['label' => 'Code'], 'state' => ['label' => $label . ' status'], 'total' => ['label' => 'Products', 'type' => 'number'],
            'active' => ['label' => 'Active', 'type' => 'number'], 'draft' => ['label' => 'Draft / pending', 'type' => 'number'], 'inactive' => ['label' => 'Inactive / discontinued', 'type' => 'number'],
            'archived' => ['label' => 'Archived', 'type' => 'number'], 'variants' => ['label' => 'Variants', 'type' => 'number']],
            'rows' => $rows, 'totals' => ['name' => 'Total'] + $totals,
            'notice' => $by === 'category' ? 'A category counts the products of its sub-categories too; the total counts each product once.' : null];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function variants(array $f, array $scope, string $date): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql($f, $scope);
        $variants = new VariantService($this->db);
        $pricing = new PricingService($this->db);
        $rows = [];
        foreach ($this->db->select("SELECT p.id, p.product_code, p.name FROM products p WHERE {$w} AND p.has_variants = 1 ORDER BY p.name", $p) as $pr) {
            foreach ($variants->forProduct((int) $pr['id']) as $v) {
                $sell = $pricing->priceOn((int) $pr['id'], (int) $v['id'], 'standard_selling', $date);
                $buy = $pricing->priceOn((int) $pr['id'], (int) $v['id'], 'standard_purchase', $date);
                $rows[] = ['code' => $v['variant_code'], 'product' => $pr['product_code'] . ' ' . $pr['name'], 'variant' => $v['name'], 'sku' => $v['sku'] ?? '', 'barcode' => $v['barcode'] ?? '',
                    'attributes' => implode(', ', array_map(static fn (array $a): string => $a['attribute'] . ': ' . $a['value'], $v['attributes'])), 'status' => VariantService::STATUSES[$v['status']] ?? $v['status'],
                    'purchase' => $buy !== null ? Money::fromDb($buy['amount']) : null, 'selling' => $sell !== null ? Money::fromDb($sell['amount']) : null, 'uuid' => $v['uuid']];
            }
        }
        return ['columns' => ['code' => ['label' => 'Variant code'], 'product' => ['label' => 'Product'], 'variant' => ['label' => 'Variant'], 'sku' => ['label' => 'SKU'], 'barcode' => ['label' => 'Barcode'],
            'attributes' => ['label' => 'Attributes'], 'status' => ['label' => 'Status'], 'purchase' => ['label' => 'Std. purchase (INR)', 'type' => 'money', 'field' => ['products', 'purchase_cost']],
            'selling' => ['label' => 'Std. selling (INR)', 'type' => 'money', 'field' => ['products', 'selling_price']], 'uuid' => ['label' => 'Stable ID']],
            'rows' => $rows, 'totals' => ['code' => 'Total (' . count($rows) . ')'], 'notice' => 'Variant prices shown are variant-specific standard prices; where a variant has none, the product price applies.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function pricing(array $f, array $scope, string $date): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql($f, $scope);
        $type = (string) ($f['price_type'] ?? '');
        $extra = isset(PricingService::TYPES[$type]) ? ' AND pr.price_type = ?' : '';
        $params = array_merge($this->supplierScope[1], [$date, $date], $p, $extra !== '' ? [$type] : []);
        $rows = [];
        foreach ($this->db->select("SELECT pr.*, p.product_code, p.name AS product_name, v.name AS variant_name, CASE WHEN s.id IS NULL THEN NULL WHEN {$this->supplierScope[0]} THEN s.name ELSE 'Restricted supplier' END AS supplier_name, g.gstin FROM product_prices pr JOIN products p ON p.id = pr.product_id
            LEFT JOIN product_variants v ON v.id = pr.variant_id LEFT JOIN suppliers s ON s.id = pr.supplier_id LEFT JOIN gst_registrations g ON g.id = pr.gst_registration_id
            WHERE pr.status IN ('active', 'superseded') AND pr.effective_from <= ? AND (pr.effective_until IS NULL OR pr.effective_until >= ?) AND {$w}{$extra}
            ORDER BY p.name, v.name, pr.price_type", $params) as $r) {
            $purchase = in_array($r['price_type'], PricingService::PURCHASE_TYPES, true);
            $rows[] = ['product' => $r['product_code'] . ' ' . $r['product_name'], 'variant' => $r['variant_name'] ?? '', 'type' => PricingService::TYPES[$r['price_type']],
                'scope' => implode(' · ', array_filter([$r['supplier_name'], $r['gstin'], $r['sales_channel']])), 'currency' => $r['currency'],
                'purchase_amount' => $purchase ? Money::fromDb($r['amount']) : null, 'selling_amount' => $purchase ? null : Money::fromDb($r['amount']),
                'from' => format_date($r['effective_from']), 'until' => $r['effective_until'] ? format_date($r['effective_until']) : 'open'];
        }
        return ['columns' => ['product' => ['label' => 'Product'], 'variant' => ['label' => 'Variant'], 'type' => ['label' => 'Price type'], 'scope' => ['label' => 'Supplier / GSTIN / channel'],
            'currency' => ['label' => 'Cur.'], 'purchase_amount' => ['label' => 'Purchase price', 'type' => 'money', 'field' => ['products', 'purchase_cost']],
            'selling_amount' => ['label' => 'Selling price', 'type' => 'money', 'field' => ['products', 'selling_price']], 'from' => ['label' => 'From'], 'until' => ['label' => 'Until']],
            'rows' => $rows, 'notice' => 'Amounts are in the currency shown on each row. Price history (all versions) is on each product\'s Pricing tab.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function tax(array $f, array $scope, string $date): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql($f, $scope);
        $rows = [];
        foreach ($this->db->select("SELECT t.*, p.product_code, p.name AS product_name, v.name AS variant_name, g.gstin, r.name AS rate_name, c.name AS category_name FROM product_tax_configs t
            JOIN products p ON p.id = t.product_id LEFT JOIN product_variants v ON v.id = t.variant_id LEFT JOIN gst_registrations g ON g.id = t.gst_registration_id
            LEFT JOIN gst_tax_rates r ON r.id = t.gst_rate_id JOIN product_tax_categories c ON c.id = t.tax_category_id
            WHERE t.status IN ('active', 'superseded') AND t.effective_from <= ? AND (t.effective_until IS NULL OR t.effective_until >= ?) AND {$w} ORDER BY p.name, v.name, g.gstin", array_merge([$date, $date], $p)) as $r) {
            $rows[] = ['product' => $r['product_code'] . ' ' . $r['product_name'], 'variant' => $r['variant_name'] ?? '', 'gstin' => $r['gstin'] ?? 'All mapped registrations',
                'hsn' => $r['hsn_code'] ?? '', 'sac' => $r['sac_code'] ?? '', 'rate' => $r['rate_name'] ?? '—', 'category' => $r['category_name'], 'applicability' => TaxConfigService::APPLICABILITY[$r['applicability']],
                'inclusion' => $r['price_inclusion'] === 'inclusive' ? 'Inclusive' : 'Exclusive', 'from' => format_date($r['effective_from']), 'until' => $r['effective_until'] ? format_date($r['effective_until']) : 'open'];
        }
        return ['columns' => ['product' => ['label' => 'Product'], 'variant' => ['label' => 'Variant'], 'gstin' => ['label' => 'GST registration'], 'hsn' => ['label' => 'HSN', 'field' => ['products', 'tax_configuration']],
            'sac' => ['label' => 'SAC', 'field' => ['products', 'tax_configuration']], 'rate' => ['label' => 'GST rate', 'field' => ['products', 'tax_configuration']], 'category' => ['label' => 'Tax category'],
            'applicability' => ['label' => 'Applicability'], 'inclusion' => ['label' => 'Prices'], 'from' => ['label' => 'From'], 'until' => ['label' => 'Until']],
            'rows' => $rows, 'notice' => 'HSN/SAC codes are checked for format only; they are not verified with any government system. No tax is calculated here.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function mappings(array $f, array $scope, string $date): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql($f, $scope);
        $status = (string) ($f['mapping'] ?? '');
        $pricing = new PricingService($this->db);
        $rows = [];
        foreach ($this->db->select("SELECT m.*, p.product_code, p.name AS product_name, v.name AS variant_name, s.supplier_code, s.name AS supplier_name FROM product_supplier_mappings m
            JOIN products p ON p.id = m.product_id LEFT JOIN product_variants v ON v.id = m.variant_id JOIN suppliers s ON s.id = m.supplier_id
            WHERE {$w} AND {$this->supplierScope[0]}" . ($status === 'all' ? '' : " AND m.status <> 'ended'") . ' ORDER BY p.name, v.name, m.is_preferred DESC, m.priority', array_merge($p, $this->supplierScope[1])) as $r) {
            $price = $pricing->priceOn((int) $r['product_id'], $r['variant_id'] !== null ? (int) $r['variant_id'] : null, 'supplier_purchase', $date, (int) $r['supplier_id']);
            $rows[] = ['product' => $r['product_code'] . ' ' . $r['product_name'], 'variant' => $r['variant_name'] ?? 'All variants', 'supplier' => $r['supplier_code'] . ' ' . $r['supplier_name'],
                'supplier_code' => trim(($r['supplier_product_code'] ?? '') . ' ' . ($r['supplier_sku'] ? '/ ' . $r['supplier_sku'] : '')), 'moq' => $r['min_order_qty'] !== null ? rtrim(rtrim((string) $r['min_order_qty'], '0'), '.') : '',
                'lead' => $r['lead_time_days'] !== null ? $r['lead_time_days'] . ' d' : '', 'preferred' => (int) $r['is_preferred'] ? 'Preferred' : '', 'priority' => (int) $r['priority'],
                'price' => $price !== null ? Money::fromDb($price['amount']) : null, 'status' => ucfirst($r['status']), 'from' => format_date($r['effective_from'])];
        }
        return ['columns' => ['product' => ['label' => 'Product'], 'variant' => ['label' => 'Variant'], 'supplier' => ['label' => 'Supplier'],
            'supplier_code' => ['label' => 'Supplier code / SKU', 'field' => ['products', 'supplier_details']], 'moq' => ['label' => 'Min. order', 'field' => ['products', 'supplier_details']],
            'lead' => ['label' => 'Lead time', 'field' => ['products', 'supplier_details']], 'preferred' => ['label' => 'Preferred'], 'priority' => ['label' => 'Priority', 'type' => 'number'],
            'price' => ['label' => 'Purchase price', 'type' => 'money', 'field' => ['products', 'purchase_cost']], 'status' => ['label' => 'Status'], 'from' => ['label' => 'Since']],
            'rows' => $rows, 'totals' => ['product' => 'Total (' . count($rows) . ')'], 'notice' => 'The preferred supplier is chosen by people, not by price.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function inactive(array $f, array $scope): array
    {
        [$w, $p] = (new ProductService($this->db))->filterSql(['archived' => 'with', 'status' => ''] + $f, $scope);
        $rows = [];
        foreach ($this->db->select("SELECT p.*, t.name AS type_name, u.name AS by_name FROM products p JOIN product_types t ON t.id = p.product_type_id LEFT JOIN users u ON u.id = p.updated_by
            WHERE {$w} AND p.status IN ('inactive', 'discontinued', 'archived') ORDER BY p.status, p.updated_at DESC", $p) as $r) {
            $rows[] = ['code' => $r['product_code'], 'name' => $r['name'], 'sku' => $r['sku'] ?? '', 'type' => $r['type_name'], 'status' => ProductService::STATUSES[$r['status']],
                'reason' => $r['status_reason'] ?? '', 'since' => format_date($r['archived_at'] ?? $r['updated_at']), 'by' => $r['by_name'] ?? '',
                'exception' => $r['status'] === 'archived' && (int) $r['archived_use_allowed'] ? 'Allowed in new transactions' : ''];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Product'], 'sku' => ['label' => 'SKU'], 'type' => ['label' => 'Type'], 'status' => ['label' => 'Status'],
            'reason' => ['label' => 'Reason'], 'since' => ['label' => 'Since'], 'by' => ['label' => 'Changed by'], 'exception' => ['label' => 'Exception']],
            'rows' => $rows, 'totals' => ['code' => 'Total (' . count($rows) . ')']];
    }
}
