<?php

declare(strict_types=1);

namespace App\Services\Supplier;

use App\Core\App;
use App\Core\Database;
use App\Exceptions\HttpException;
use App\Services\Export\ReportFields;
use App\Services\Product\PricingService;
use App\Support\BusinessDate;
use App\Support\Money;

/**
 * The eight supplier reports, limited to the suppliers the user may see and run through
 * the user's field rules (on screen and in exports). Product details inside supplier
 * reports are limited to products the user may see; bank details appear masked and only
 * to users with suppliers.view_bank_details.
 */
final class SupplierReportService
{
    public const REPORTS = [
        'suppliers' => ['Complete supplier list', 'Every supplier with type, GSTIN, state, status, contact and number of products.'],
        'supplier_products' => ['Supplier-wise product report', 'The products each supplier supplies, with codes, preferred flag and purchase price.'],
        'gst' => ['Supplier GST details', 'GST treatment, GSTIN, PAN, state and the company GST registrations each supplier is used for.'],
        'contacts' => ['Supplier contact report', 'Contact person, mobile, email, website and business address.'],
        'payment_terms' => ['Supplier payment terms', 'Payment terms, credit period, currency and the primary bank account (masked).'],
        'purchase_prices' => ['Supplier-wise purchase prices', 'Supplier purchase prices in force on a date.'],
        'no_products' => ['Suppliers without products', 'Suppliers that are not linked to any product.'],
        'status' => ['Active and inactive suppliers', 'Suppliers by status with the reason for the last status change.'],
    ];

    public function __construct(private readonly Database $db)
    {
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $f @return array<string, mixed> */
    public function run(array $user, string $key, array $f): array
    {
        if (!isset(self::REPORTS[$key])) {
            throw new HttpException(404, 'Report not found.');
        }
        $scope = App::dataAccess()->constrain($user, 'suppliers', 's');
        $seesProducts = App::gate()->allows($user, 'products.view');
        $productScope = $seesProducts ? App::dataAccess()->constrain($user, 'products', 'p') : ['1 = 0', []];
        $date = BusinessDate::isValid((string) ($f['as_of'] ?? '')) ? (string) $f['as_of'] : BusinessDate::today();
        $out = match ($key) {
            'suppliers' => $this->suppliers($f, $scope),
            'supplier_products' => $this->products($f, $scope, $productScope, $date, false, $seesProducts),
            'gst' => $this->gst($f, $scope),
            'contacts' => $this->contacts($f, $scope),
            'payment_terms' => $this->terms($f, $scope, App::gate()->allows($user, 'suppliers.view_bank_details')),
            'purchase_prices' => $this->products($f, $scope, $productScope, $date, true, $seesProducts),
            'no_products' => $this->suppliers(['linked' => 'no'] + $f, $scope),
            'status' => $this->status($f, $scope),
        };
        $out += ['totals' => null, 'notice' => null];
        $out = ReportFields::apply($user, $out);
        $out['title'] = self::REPORTS[$key][0];
        $out['meta'] = [App::dataAccess()->resolve($user, 'suppliers')->describe() . ' · generated by ' . $user['name'] . ' · ' . format_datetime(now())];
        if ($key === 'purchase_prices') {
            $out['meta'][] = 'Prices in force on ' . BusinessDate::format($date);
        }
        return $out;
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return list<array<string, mixed>> */
    private function list(array $f, array $scope): array
    {
        [$w, $p] = (new SupplierService($this->db))->filterSql($f, $scope);
        return $this->db->select("SELECT s.*, t.name AS type_name, st.name AS state_name, st.code AS state_code,
                (SELECT COUNT(DISTINCT m.product_id) FROM product_supplier_mappings m WHERE m.supplier_id = s.id AND m.status = 'active') AS products
            FROM suppliers s JOIN supplier_types t ON t.id = s.supplier_type_id LEFT JOIN gst_states st ON st.id = s.gst_state_id WHERE {$w} ORDER BY s.name", $p);
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function suppliers(array $f, array $scope): array
    {
        $rows = [];
        foreach ($this->list($f, $scope) as $s) {
            $rows[] = ['code' => $s['supplier_code'], 'name' => $s['name'], 'legal_name' => $s['legal_name'], 'type' => $s['type_name'], 'gstin' => $s['gstin'] ?? '',
                'treatment' => SupplierService::GST_TREATMENTS[$s['gst_treatment']], 'state' => $s['state_name'] ?? ($s['country'] !== 'IN' ? $s['country'] : ''),
                'status' => SupplierService::STATUSES[$s['status']], 'contact_person' => $s['contact_person'] ?? '', 'contact_phone' => $s['mobile'] ?? '', 'contact_email' => $s['email'] ?? '',
                'products' => (int) $s['products'], 'uuid' => $s['uuid']];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Supplier'], 'legal_name' => ['label' => 'Legal name'], 'type' => ['label' => 'Type'],
            'gstin' => ['label' => 'GSTIN', 'field' => ['suppliers', 'gstin']], 'treatment' => ['label' => 'GST treatment'], 'state' => ['label' => 'State'], 'status' => ['label' => 'Status'],
            'contact_person' => ['label' => 'Contact', 'field' => ['suppliers', 'contact_person']], 'contact_phone' => ['label' => 'Mobile', 'field' => ['suppliers', 'contact_phone']],
            'contact_email' => ['label' => 'Email', 'field' => ['suppliers', 'contact_email']], 'products' => ['label' => 'Products', 'type' => 'number'], 'uuid' => ['label' => 'Stable ID']],
            'rows' => $rows, 'totals' => ['code' => 'Total (' . count($rows) . ')']];
    }

    /**
     * @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @param array{0: string, 1: list<mixed>} $productScope
     * @return array<string, mixed>
     */
    private function products(array $f, array $scope, array $productScope, string $date, bool $pricesOnly, bool $seesProducts): array
    {
        [$sw, $sp] = (new SupplierService($this->db))->filterSql($f, $scope);
        [$pw, $pp] = $productScope;
        $pricing = new PricingService($this->db);
        $rows = [];
        $mapStatus = $pricesOnly ? " AND m.status = 'active'" : (($f['mapping'] ?? '') === 'all' ? '' : " AND m.status <> 'ended'");
        foreach ($this->db->select("SELECT m.*, s.supplier_code, s.name AS supplier_name, p.product_code, p.name AS product_name, p.sku AS product_sku, v.name AS variant_name, v.sku AS variant_sku
            FROM product_supplier_mappings m JOIN suppliers s ON s.id = m.supplier_id JOIN products p ON p.id = m.product_id LEFT JOIN product_variants v ON v.id = m.variant_id
            WHERE {$sw} AND {$pw}{$mapStatus} ORDER BY s.name, p.name, v.name", array_merge($sp, $pp)) as $r) {
            $price = $pricing->priceOn((int) $r['product_id'], $r['variant_id'] !== null ? (int) $r['variant_id'] : null, 'supplier_purchase', $date, (int) $r['supplier_id']);
            if ($pricesOnly && $price === null) {
                continue;
            }
            $priceRow = $price !== null ? $this->db->first('SELECT effective_from, effective_until FROM product_prices WHERE id = ?', [$price['id']]) : null;
            $row = ['supplier' => $r['supplier_code'] . ' ' . $r['supplier_name'], 'product' => $r['product_code'] . ' ' . $r['product_name'], 'variant' => $r['variant_name'] ?? 'All variants',
                'sku' => $r['variant_sku'] ?? $r['product_sku'] ?? '', 'currency' => $price['currency'] ?? '', 'price' => $price !== null ? Money::fromDb($price['amount']) : null];
            if ($pricesOnly) {
                $row += ['from' => $priceRow ? format_date($priceRow['effective_from']) : '', 'until' => $priceRow && $priceRow['effective_until'] ? format_date($priceRow['effective_until']) : 'open'];
            } else {
                $row += ['supplier_code' => trim(($r['supplier_product_code'] ?? '') . ($r['supplier_sku'] ? ' / ' . $r['supplier_sku'] : '')), 'preferred' => (int) $r['is_preferred'] ? 'Preferred' : '',
                    'lead' => $r['lead_time_days'] !== null ? $r['lead_time_days'] . ' d' : '', 'status' => ucfirst($r['status'])];
            }
            $rows[] = $row;
        }
        $cols = ['supplier' => ['label' => 'Supplier'], 'product' => ['label' => 'Product'], 'variant' => ['label' => 'Variant'], 'sku' => ['label' => 'SKU']];
        $cols += $pricesOnly
            ? ['currency' => ['label' => 'Cur.'], 'price' => ['label' => 'Purchase price', 'type' => 'money', 'field' => ['products', 'purchase_cost']], 'from' => ['label' => 'From'], 'until' => ['label' => 'Until']]
            : ['supplier_code' => ['label' => 'Supplier code / SKU', 'field' => ['products', 'supplier_details']], 'preferred' => ['label' => 'Preferred'], 'lead' => ['label' => 'Lead time', 'field' => ['products', 'supplier_details']],
                'currency' => ['label' => 'Cur.'], 'price' => ['label' => 'Purchase price', 'type' => 'money', 'field' => ['products', 'purchase_cost']], 'status' => ['label' => 'Mapping']];
        return ['columns' => $cols, 'rows' => $rows, 'totals' => ['supplier' => 'Total (' . count($rows) . ')'],
            'notice' => $seesProducts ? 'Only products you may see are listed.' : 'You do not have access to products, so no product rows are shown.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function gst(array $f, array $scope): array
    {
        $rows = [];
        foreach ($this->list($f, $scope) as $s) {
            $regs = $this->db->select("SELECT g.gstin FROM supplier_gst_mappings m JOIN gst_registrations g ON g.id = m.gst_registration_id WHERE m.supplier_id = ? AND m.status = 'active' ORDER BY g.gstin", [$s['id']]);
            $rows[] = ['code' => $s['supplier_code'], 'name' => $s['name'], 'legal_name' => $s['legal_name'], 'treatment' => SupplierService::GST_TREATMENTS[$s['gst_treatment']],
                'gstin' => $s['gstin'] ?? '', 'pan' => $s['pan'] ?? '', 'state' => $s['state_name'] ? $s['state_code'] . ' ' . $s['state_name'] : '', 'our_gstins' => implode(', ', array_column($regs, 'gstin'))];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Supplier'], 'legal_name' => ['label' => 'Legal name'], 'treatment' => ['label' => 'GST treatment'],
            'gstin' => ['label' => 'GSTIN', 'field' => ['suppliers', 'gstin']], 'pan' => ['label' => 'PAN', 'field' => ['suppliers', 'pan']], 'state' => ['label' => 'State'], 'our_gstins' => ['label' => 'Used for our GSTINs']],
            'rows' => $rows, 'notice' => 'GSTINs are checked for structure, state code, PAN segment and check character only; they are not verified with the GST portal.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function contacts(array $f, array $scope): array
    {
        $rows = [];
        foreach ($this->list($f, $scope) as $s) {
            $addr = $this->db->first("SELECT a.*, st.name AS state FROM supplier_addresses a LEFT JOIN gst_states st ON st.id = a.state_id WHERE a.supplier_id = ? AND a.status = 'active'
                ORDER BY CASE a.address_type WHEN 'business' THEN 0 ELSE 1 END, a.is_default DESC LIMIT 1", [$s['id']]);
            $rows[] = ['code' => $s['supplier_code'], 'name' => $s['name'], 'contact_person' => $s['contact_person'] ?? '', 'contact_phone' => $s['mobile'] ?? '', 'contact_email' => $s['email'] ?? '',
                'website' => $s['website'] ?? '', 'addresses' => $addr !== null ? SupplierDetailService::format($addr) : '', 'status' => SupplierService::STATUSES[$s['status']]];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Supplier'], 'contact_person' => ['label' => 'Contact person', 'field' => ['suppliers', 'contact_person']],
            'contact_phone' => ['label' => 'Mobile', 'field' => ['suppliers', 'contact_phone']], 'contact_email' => ['label' => 'Email', 'field' => ['suppliers', 'contact_email']], 'website' => ['label' => 'Website'],
            'addresses' => ['label' => 'Business address', 'field' => ['suppliers', 'addresses']], 'status' => ['label' => 'Status']], 'rows' => $rows];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function terms(array $f, array $scope, bool $bank): array
    {
        $rows = [];
        foreach ($this->list($f, $scope) as $s) {
            $b = $bank ? $this->db->first("SELECT bank_name, account_number_last4, ifsc_code FROM supplier_bank_details WHERE supplier_id = ? AND status = 'active' ORDER BY is_primary DESC, id LIMIT 1", [$s['id']]) : null;
            $rows[] = ['code' => $s['supplier_code'], 'name' => $s['name'], 'payment_terms' => $s['payment_terms'] ?? '', 'credit' => $s['credit_period_days'] !== null ? $s['credit_period_days'] . ' days' : '',
                'currency' => $s['default_currency'], 'bank' => $b !== null ? $b['bank_name'] . ' · XXXXXX' . $b['account_number_last4'] . ($b['ifsc_code'] ? ' · ' . $b['ifsc_code'] : '') : ($bank ? '—' : 'Not permitted')];
        }
        $cols = ['code' => ['label' => 'Code'], 'name' => ['label' => 'Supplier'], 'payment_terms' => ['label' => 'Payment terms', 'field' => ['suppliers', 'payment_terms']],
            'credit' => ['label' => 'Credit period', 'field' => ['suppliers', 'payment_terms']], 'currency' => ['label' => 'Currency'], 'bank' => ['label' => 'Primary bank account', 'field' => ['suppliers', 'bank_account_number']]];
        if (!$bank) {
            unset($cols['bank']);
            foreach ($rows as &$r) {
                unset($r['bank']);
            }
        }
        return ['columns' => $cols, 'rows' => $rows, 'notice' => 'Account numbers are always masked in reports.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function status(array $f, array $scope): array
    {
        $rows = [];
        $counts = [];
        foreach ($this->list(['archived' => ($f['status'] ?? '') === 'archived' ? 'only' : 'with'] + $f, $scope) as $s) {
            $counts[$s['status']] = ($counts[$s['status']] ?? 0) + 1;
            $rows[] = ['code' => $s['supplier_code'], 'name' => $s['name'], 'type' => $s['type_name'], 'status' => SupplierService::STATUSES[$s['status']], 'reason' => $s['status_reason'] ?? '',
                'updated' => format_date($s['updated_at']), 'products' => (int) $s['products']];
        }
        usort($rows, static fn (array $a, array $b): int => [$a['status'], $a['name']] <=> [$b['status'], $b['name']]);
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Supplier'], 'type' => ['label' => 'Type'], 'status' => ['label' => 'Status'], 'reason' => ['label' => 'Reason'],
            'updated' => ['label' => 'Last change'], 'products' => ['label' => 'Products', 'type' => 'number']],
            'rows' => $rows, 'notice' => implode(' · ', array_map(static fn (string $k, int $n): string => SupplierService::STATUSES[$k] . ': ' . $n, array_keys($counts), $counts)) ?: null];
    }
}
