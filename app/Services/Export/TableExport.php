<?php

declare(strict_types=1);

namespace App\Services\Export;

use App\Core\Response;
use App\Exceptions\DomainRuleException;
use App\Support\Money;

/**
 * Renders one table to CSV, Excel (.xlsx) or PDF without third-party packages.
 *
 * Columns: key => ['label' => string, 'type' => 'text'|'money'|'number'|'date']
 * Rows:    key => value. Money values are integer paise; anything that is not
 *          an int in a money column (e.g. a masked "₹ ••••••") is written as text.
 * Callers remove hidden columns and mask values BEFORE calling this class.
 */
final class TableExport
{
    public const FORMATS = ['csv' => 'CSV', 'xlsx' => 'Excel', 'pdf' => 'PDF'];

    /**
     * @param array<string, array{label: string, type?: string}> $columns
     * @param list<array<string, mixed>> $rows
     * @param list<string> $meta lines printed under the title (filters, generated by…)
     * @param array<string, mixed>|null $totals optional totals row
     */
    public function __construct(
        private readonly string $title,
        private readonly array $columns,
        private readonly array $rows,
        private readonly array $meta = [],
        private readonly ?array $totals = null,
    ) {
    }

    public function response(string $format, string $filenameBase): Response
    {
        $name = preg_replace('/[^a-z0-9-]+/', '-', strtolower($filenameBase)) . '-' . gmdate('Ymd-His');
        return match ($format) {
            'csv' => new Response($this->csv(), 200, ['Content-Type' => 'text/csv; charset=UTF-8', 'Content-Disposition' => "attachment; filename=\"{$name}.csv\"", 'X-Content-Type-Options' => 'nosniff', 'Cache-Control' => 'private, no-store']),
            'xlsx' => new Response($this->xlsx(), 200, ['Content-Type' => 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', 'Content-Disposition' => "attachment; filename=\"{$name}.xlsx\"", 'X-Content-Type-Options' => 'nosniff', 'Cache-Control' => 'private, no-store']),
            'pdf' => new Response($this->pdf(), 200, ['Content-Type' => 'application/pdf', 'Content-Disposition' => "attachment; filename=\"{$name}.pdf\"", 'X-Content-Type-Options' => 'nosniff', 'Cache-Control' => 'private, no-store']),
            default => throw new DomainRuleException('Unsupported export format.'),
        };
    }

    // ------------------------------------------------------------------ CSV

    public function csv(): string
    {
        $out = fopen('php://temp', 'w+');
        fwrite($out, "\xEF\xBB\xBF");
        fputcsv($out, [$this->title], ',', '"', '');
        foreach ($this->meta as $m) {
            fputcsv($out, [$m], ',', '"', '');
        }
        fputcsv($out, [], ',', '"', '');
        fputcsv($out, array_column($this->columns, 'label'), ',', '"', '');
        foreach (array_merge($this->rows, $this->totals !== null ? [$this->totals] : []) as $row) {
            $line = [];
            foreach ($this->columns as $key => $col) {
                $v = $row[$key] ?? '';
                if (($col['type'] ?? 'text') === 'money' && is_int($v)) {
                    $v = Money::toDb($v);
                }
                $v = is_bool($v) ? ($v ? 'Yes' : 'No') : (string) $v;
                $line[] = preg_match('/^[=+\-@\t\r]/', $v) === 1 && !is_numeric($v) ? "'" . $v : $v; // formula-injection guard
            }
            fputcsv($out, $line, ',', '"', '');
        }
        rewind($out);
        $csv = (string) stream_get_contents($out);
        fclose($out);
        return $csv;
    }

    // ------------------------------------------------------------------ XLSX

    public function xlsx(): string
    {
        if (!class_exists(\ZipArchive::class)) {
            throw new DomainRuleException('Excel export needs the PHP zip extension.');
        }
        $x = static fn (string $s): string => htmlspecialchars((string) preg_replace('/[^\x{9}\x{A}\x{D}\x{20}-\x{D7FF}\x{E000}-\x{FFFD}]/u', '', $s), ENT_XML1 | ENT_QUOTES, 'UTF-8');
        $colName = static function (int $i): string {
            $n = '';
            for ($i++; $i > 0; $i = intdiv($i - 1, 26)) {
                $n = chr(65 + ($i - 1) % 26) . $n;
            }
            return $n;
        };
        $keys = array_keys($this->columns);
        $rowsXml = '';
        $r = 1;
        $cell = static function (string $ref, mixed $v, string $type, int $style = 0) use ($x): string {
            if ($type === 'money' && is_int($v)) {
                return "<c r=\"{$ref}\" s=\"2\"><v>" . Money::toDb($v) . '</v></c>';
            }
            if ($type === 'number' && (is_int($v) || is_float($v))) {
                return "<c r=\"{$ref}\"" . ($style ? " s=\"{$style}\"" : '') . "><v>{$v}</v></c>";
            }
            $s = is_bool($v) ? ($v ? 'Yes' : 'No') : (string) ($v ?? '');
            return "<c r=\"{$ref}\" t=\"inlineStr\"" . ($style ? " s=\"{$style}\"" : '') . '><is><t xml:space="preserve">' . $x($s) . '</t></is></c>';
        };
        $rowsXml .= "<row r=\"{$r}\">" . $cell("A{$r}", $this->title, 'text', 3) . '</row>';
        foreach ($this->meta as $m) {
            $r++;
            $rowsXml .= "<row r=\"{$r}\">" . $cell("A{$r}", $m, 'text') . '</row>';
        }
        $r += 2;
        $headerRow = $r;
        $rowsXml .= "<row r=\"{$r}\">";
        foreach ($keys as $i => $k) {
            $rowsXml .= $cell($colName($i) . $r, $this->columns[$k]['label'], 'text', 1);
        }
        $rowsXml .= '</row>';
        foreach (array_merge($this->rows, $this->totals !== null ? [$this->totals] : []) as $row) {
            $r++;
            $rowsXml .= "<row r=\"{$r}\">";
            foreach ($keys as $i => $k) {
                $rowsXml .= $cell($colName($i) . $r, $row[$k] ?? '', (string) ($this->columns[$k]['type'] ?? 'text'));
            }
            $rowsXml .= '</row>';
        }
        $cols = '';
        foreach ($keys as $i => $k) {
            $w = ($this->columns[$k]['type'] ?? 'text') === 'money' ? 18 : max(10, min(45, mb_strlen($this->columns[$k]['label']) + 6));
            $cols .= '<col min="' . ($i + 1) . '" max="' . ($i + 1) . "\" width=\"{$w}\" customWidth=\"1\"/>";
        }
        $last = $colName(max(0, count($keys) - 1));
        $sheet = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>'
            . '<worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships">'
            . '<sheetViews><sheetView workbookViewId="0"><pane ySplit="' . $headerRow . '" topLeftCell="A' . ($headerRow + 1) . '" activePane="bottomLeft" state="frozen"/></sheetView></sheetViews>'
            . "<cols>{$cols}</cols><sheetData>{$rowsXml}</sheetData>"
            . ($r > $headerRow ? "<autoFilter ref=\"A{$headerRow}:{$last}{$r}\"/>" : '')
            . '</worksheet>';
        $sheetName = $x(mb_substr((string) preg_replace('/[\\\\\/?*\[\]:]/', ' ', $this->title), 0, 31));
        $files = [
            '[Content_Types].xml' => '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Types xmlns="http://schemas.openxmlformats.org/package/2006/content-types"><Default Extension="rels" ContentType="application/vnd.openxmlformats-package.relationships+xml"/><Default Extension="xml" ContentType="application/xml"/><Override PartName="/xl/workbook.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml"/><Override PartName="/xl/worksheets/sheet1.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.worksheet+xml"/><Override PartName="/xl/styles.xml" ContentType="application/vnd.openxmlformats-officedocument.spreadsheetml.styles+xml"/></Types>',
            '_rels/.rels' => '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/officeDocument" Target="xl/workbook.xml"/></Relationships>',
            'xl/workbook.xml' => '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><workbook xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"><sheets><sheet name="' . ($sheetName !== '' ? $sheetName : 'Report') . '" sheetId="1" r:id="rId1"/></sheets>' . ($r > $headerRow ? '<definedNames><definedName name="_xlnm._FilterDatabase" localSheetId="0" hidden="1">\'' . ($sheetName !== '' ? $sheetName : 'Report') . "'!\$A\${$headerRow}:\${$last}\${$r}</definedName></definedNames>" : '') . '</workbook>',
            'xl/_rels/workbook.xml.rels' => '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><Relationships xmlns="http://schemas.openxmlformats.org/package/2006/relationships"><Relationship Id="rId1" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/worksheet" Target="worksheets/sheet1.xml"/><Relationship Id="rId2" Type="http://schemas.openxmlformats.org/officeDocument/2006/relationships/styles" Target="styles.xml"/></Relationships>',
            'xl/styles.xml' => '<?xml version="1.0" encoding="UTF-8" standalone="yes"?><styleSheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><numFmts count="1"><numFmt numFmtId="164" formatCode="#,##0.00"/></numFmts><fonts count="3"><font><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="11"/><name val="Calibri"/></font><font><b/><sz val="14"/><name val="Calibri"/></font></fonts><fills count="3"><fill><patternFill patternType="none"/></fill><fill><patternFill patternType="gray125"/></fill><fill><patternFill patternType="solid"><fgColor rgb="FFEFF5FF"/></patternFill></fill></fills><borders count="1"><border><left/><right/><top/><bottom/><diagonal/></border></borders><cellStyleXfs count="1"><xf numFmtId="0" fontId="0" fillId="0" borderId="0"/></cellStyleXfs><cellXfs count="4"><xf numFmtId="0" fontId="0" fillId="0" borderId="0" xfId="0"/><xf numFmtId="0" fontId="1" fillId="2" borderId="0" xfId="0" applyFont="1" applyFill="1"/><xf numFmtId="164" fontId="0" fillId="0" borderId="0" xfId="0" applyNumberFormat="1"/><xf numFmtId="0" fontId="2" fillId="0" borderId="0" xfId="0" applyFont="1"/></cellXfs><cellStyles count="1"><cellStyle name="Normal" xfId="0" builtinId="0"/></cellStyles></styleSheet>',
            'xl/worksheets/sheet1.xml' => $sheet,
        ];
        $tmp = tempnam(sys_get_temp_dir(), 'xlsx');
        $zip = new \ZipArchive();
        if ($zip->open($tmp, \ZipArchive::OVERWRITE) !== true) {
            throw new DomainRuleException('Could not build the Excel file.');
        }
        foreach ($files as $path => $content) {
            $zip->addFromString($path, $content);
        }
        $zip->close();
        $data = (string) file_get_contents($tmp);
        @unlink($tmp);
        return $data;
    }

    // ------------------------------------------------------------------ PDF

    public function pdf(): string
    {
        $pdf = new SimplePdf();
        $keys = array_keys($this->columns);
        $text = function (mixed $v, string $type): string {
            if ($type === 'money' && is_int($v)) {
                return Money::format($v, 'Rs. ');
            }
            return is_bool($v) ? ($v ? 'Yes' : 'No') : (string) ($v ?? '');
        };
        $body = [];
        foreach ($this->rows as $row) {
            $body[] = array_map(fn (string $k): string => $text($row[$k] ?? '', (string) ($this->columns[$k]['type'] ?? 'text')), $keys);
        }
        $totals = $this->totals !== null ? array_map(fn (string $k): string => $text($this->totals[$k] ?? '', (string) ($this->columns[$k]['type'] ?? 'text')), $keys) : null;
        $align = array_map(fn (string $k): string => in_array($this->columns[$k]['type'] ?? 'text', ['money', 'number'], true) ? 'R' : 'L', $keys);
        return $pdf->table($this->title, $this->meta, array_column($this->columns, 'label'), $body, $align, $totals);
    }
}
