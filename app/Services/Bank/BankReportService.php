<?php

declare(strict_types=1);

namespace App\Services\Bank;

use App\Core\App;
use App\Core\Database;
use App\Exceptions\HttpException;
use App\Services\Authorization\FieldPolicy;
use App\Support\BusinessDate;
use App\Support\Money;

/**
 * The eleven bank reports. Every report is limited to the bank accounts the user may see
 * (record scope) and applies the user's field rules, on screen and in CSV / Excel / PDF.
 * Internal transfers are shown separately and never counted as money received or paid.
 */
final class BankReportService
{
    public const REPORTS = [
        'summary' => ['Bank account summary', 'Every account with bank, type, status, mappings and current balance.'],
        'balances' => ['Account-wise balance report', 'Opening balance, deposits, withdrawals, transfers, charges, interest, adjustments and balance per account.'],
        'transactions' => ['Bank transaction report', 'All ledger entries with filters by account, type, status, partner, GST registration and date.'],
        'deposits_withdrawals' => ['Deposits and withdrawals', 'Deposits and withdrawals only, with partner contribution references.'],
        'transfers' => ['Internal transfer report', 'Transfers between the company\'s own accounts. Not income or expense.'],
        'partner_accounts' => ['Partner-linked bank accounts', 'Which partners are associated with which accounts, and how.'],
        'gst_accounts' => ['GST-wise bank accounts', 'Bank accounts per GST registration, primary and secondary.'],
        'cash_flow' => ['Monthly cash-flow summary', 'Money received and paid per month (internal transfers excluded).'],
        'reconciliation' => ['Bank reconciliation report', 'Reconciliations with matched, ignored and outstanding items and the balance difference.'],
        'unmatched' => ['Unmatched statement transactions', 'Imported statement lines not yet matched to a ledger entry.'],
        'charges_interest' => ['Bank charges and interest', 'Bank charges and interest entries with totals per account.'],
    ];

    public function __construct(private readonly Database $db)
    {
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $f @return array<string, mixed> */
    public function run(array $user, string $key, array $f): array
    {
        if (!isset(self::REPORTS[$key])) {
            throw new HttpException(404, 'Report not found.');
        }
        $scope = App::dataAccess()->constrain($user, 'bank_accounts', 'a');
        $out = match ($key) {
            'summary' => $this->summary($f, $scope),
            'balances' => $this->balances($f, $scope),
            // 'type' is the account type elsewhere; the ledger entry type arrives as txn_type.
            'transactions' => $this->transactions(array_merge($f, ['type' => $f['txn_type'] ?? '']), $scope),
            'deposits_withdrawals' => $this->transactions(['types' => ['deposit', 'withdrawal']] + array_merge($f, ['type' => '']), $scope, true),
            'transfers' => $this->transfers($user, $f),
            'partner_accounts' => $this->partnerAccounts($f, $scope),
            'gst_accounts' => $this->gstAccounts($f, $scope),
            'cash_flow' => $this->cashFlow($f, $scope),
            'reconciliation' => $this->reconciliations($f, $scope),
            'unmatched' => $this->unmatched($f, $scope),
            'charges_interest' => $this->transactions(['types' => ['bank_charges', 'interest']] + array_merge($f, ['type' => '']), $scope),
        };
        $out += ['totals' => null, 'notice' => null];
        $out = $this->applyFields($user, $out);
        $out['title'] = self::REPORTS[$key][0];
        $out['meta'] = array_merge([App::dataAccess()->resolve($user, 'bank_accounts')->describe() . ' · generated by ' . $user['name'] . ' · ' . format_datetime(now())], $this->describe($f));
        return $out;
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return list<array<string, mixed>> */
    private function accounts(array $f, array $scope): array
    {
        [$w, $p] = (new BankAccountService($this->db))->filterSql($f, $scope);
        return $this->db->select("SELECT a.*, t.name AS type_name,
                (SELECT COUNT(*) FROM bank_account_partner_mappings m WHERE m.bank_account_id = a.id AND m.status = 'active') AS partners,
                (SELECT COUNT(*) FROM bank_account_gst_mappings m WHERE m.bank_account_id = a.id AND m.status = 'active') AS gst
            FROM bank_accounts a JOIN bank_account_types t ON t.id = a.account_type_id WHERE {$w} ORDER BY a.is_central_funding DESC, a.display_name", $p);
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function summary(array $f, array $scope): array
    {
        $accounts = $this->accounts($f, $scope);
        $ids = array_map(static fn (array $a): int => (int) $a['id'], $accounts);
        $bal = (new BankLedgerService($this->db))->balances($ids);
        $rec = (new BankReconciliationService($this->db))->lastCompleted($ids);
        $rows = [];
        $total = 0;
        foreach ($accounts as $a) {
            $b = $bal[(int) $a['id']] ?? 0;
            $total += $a['currency'] === 'INR' ? $b : 0;
            $rows[] = ['code' => $a['account_code'], 'name' => $a['display_name'] . ((int) $a['is_central_funding'] ? ' (central)' : ''), 'bank' => $a['bank_name'], 'account_number' => 'XXXXXX' . $a['account_number_last4'],
                'ifsc_code' => $a['ifsc_code'], 'type' => $a['type_name'], 'status' => BankAccountService::STATUSES[$a['status']] . ((int) $a['is_archived'] ? ' (archived)' : ''),
                'partners' => (int) $a['partners'], 'gst' => (int) $a['gst'], 'currency' => $a['currency'], 'current_balance' => $b, 'reconciled' => isset($rec[(int) $a['id']]) ? format_date($rec[(int) $a['id']]) : '—'];
        }
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Account'], 'bank' => ['label' => 'Bank'], 'account_number' => ['label' => 'Account no.', 'field' => ['bank_accounts', 'account_number']],
            'ifsc_code' => ['label' => 'IFSC', 'field' => ['bank_accounts', 'ifsc_code']], 'type' => ['label' => 'Type'], 'status' => ['label' => 'Status'], 'partners' => ['label' => 'Partners', 'type' => 'number'],
            'gst' => ['label' => 'GST regs', 'type' => 'number'], 'currency' => ['label' => 'Cur.'], 'current_balance' => ['label' => 'Balance', 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']], 'reconciled' => ['label' => 'Reconciled to']],
            'rows' => $rows, 'totals' => ['code' => 'Total (' . count($rows) . ')', 'current_balance' => $total], 'notice' => 'Totals include INR accounts only.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function balances(array $f, array $scope): array
    {
        $ledger = new BankLedgerService($this->db);
        $asOf = BusinessDate::isValid((string) ($f['to'] ?? '')) ? (string) $f['to'] : null;
        $rows = [];
        $keys = ['opening', 'deposits', 'withdrawals', 'transfer_in', 'transfer_out', 'bank_charges', 'interest', 'adjustments', 'balance'];
        $totals = array_fill_keys($keys, 0);
        foreach ($this->accounts($f, $scope) as $a) {
            $b = $ledger->breakdown((int) $a['id']);
            $b['adjustments'] += $b['opening_adjustments'];
            if ($asOf !== null) {
                $b['balance'] = $ledger->balance((int) $a['id'], $asOf);
            }
            $row = ['code' => $a['account_code'], 'name' => $a['display_name'], 'currency' => $a['currency']];
            foreach ($keys as $k) {
                $row[$k] = $b[$k];
                $totals[$k] += $a['currency'] === 'INR' ? $b[$k] : 0;
            }
            $rows[] = $row;
        }
        $money = static fn (string $l, ?string $field = 'current_balance'): array => ['label' => $l, 'type' => 'money', 'field' => ['bank_accounts', $field]];
        return ['columns' => ['code' => ['label' => 'Code'], 'name' => ['label' => 'Account'], 'currency' => ['label' => 'Cur.'], 'opening' => $money('Opening', 'opening_balance'), 'deposits' => $money('Deposits'),
            'withdrawals' => $money('Withdrawals'), 'transfer_in' => $money('Transfers in'), 'transfer_out' => $money('Transfers out'), 'bank_charges' => $money('Charges'), 'interest' => $money('Interest'),
            'adjustments' => $money('Adjustments'), 'balance' => $money($asOf ? 'Balance at ' . format_date($asOf) : 'Current balance')],
            'rows' => $rows, 'totals' => ['code' => 'Total'] + $totals, 'notice' => 'Components are all-time and net of reversals; adjustments include opening-balance adjustments. Totals include INR accounts only.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function transactions(array $f, array $scope, bool $withCapital = false): array
    {
        [$w, $p] = (new BankTransactionService($this->db))->filterSql($f, $scope);
        if (!empty($f['types'])) {
            $w .= ' AND COALESCE(o.type, t.type) IN (' . implode(',', array_fill(0, count($f['types']), '?')) . ')';
            $p = array_merge($p, $f['types']);
        }
        if (!isset(BankTransactionService::STATUSES[(string) ($f['status'] ?? '')]) && ($f['status'] ?? '') !== 'open') {
            $w .= ' AND t.status IN ' . BankLedgerService::EFFECTIVE; // default: posted entries only
        }
        $rows = [];
        $credit = 0;
        $debit = 0;
        foreach ($this->db->select("SELECT t.*, a.account_code, a.display_name AS account_name, pa.name AS partner_name, g.gstin, c.transaction_no AS capital_no, tr.transfer_no
            FROM bank_transactions t JOIN bank_accounts a ON a.id = t.bank_account_id LEFT JOIN bank_transactions o ON o.id = t.reversal_of_id LEFT JOIN partners pa ON pa.id = t.partner_id
            LEFT JOIN gst_registrations g ON g.id = t.gst_registration_id LEFT JOIN partner_capital_transactions c ON c.id = t.capital_transaction_id LEFT JOIN bank_transfers tr ON tr.id = t.transfer_id
            WHERE {$w} ORDER BY t.transaction_date, t.id LIMIT 20000", $p) as $t) {
            $amount = Money::fromDb($t['amount']);
            $t['direction'] === 'credit' ? $credit += $amount : $debit += $amount;
            $rows[] = ['no' => $t['transaction_no'], 'date' => format_date($t['transaction_date']), 'account' => $t['account_code'] . ' ' . $t['account_name'], 'type' => BankLedgerService::TYPE_LABELS[$t['type']],
                'reference' => trim(($t['reference_no'] ?? '') . ' ' . ($t['utr_cheque_no'] ?? '')) ?: '—', 'counterparty_name' => $t['counterparty_name'] ?? '', 'partner' => $t['partner_name'] ?? '',
                'capital' => $t['capital_no'] ?? ($t['transfer_no'] ?? ''), 'gstin' => $t['gstin'] ?? '', 'status' => BankTransactionService::STATUSES[$t['status']],
                'credit' => $t['direction'] === 'credit' ? $amount : null, 'debit' => $t['direction'] === 'debit' ? $amount : null];
        }
        $columns = ['no' => ['label' => 'Entry'], 'date' => ['label' => 'Date'], 'account' => ['label' => 'Account'], 'type' => ['label' => 'Type'], 'reference' => ['label' => 'Reference / UTR'],
            'counterparty_name' => ['label' => 'Counterparty', 'field' => ['bank_accounts', 'counterparty_name']], 'partner' => ['label' => 'Partner'],
            'capital' => ['label' => $withCapital ? 'Capital entry' : 'Capital / transfer ref.'], 'gstin' => ['label' => 'GSTIN'], 'status' => ['label' => 'Status'],
            'credit' => ['label' => 'Credit', 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']], 'debit' => ['label' => 'Debit', 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']]];
        return ['columns' => $columns, 'rows' => $rows, 'totals' => ['no' => 'Total (' . count($rows) . ')', 'credit' => $credit, 'debit' => $debit],
            'notice' => 'Posted entries by default (choose a status to see others). Reversal rows are listed with the type they reverse filtered in. Partner capital contributions are money received from partners, not business revenue.'];
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $f @return array<string, mixed> */
    private function transfers(array $user, array $f): array
    {
        $da = App::dataAccess();
        [$w, $p] = (new BankTransferService($this->db))->filterSql($f + ['status' => $f['status'] ?: 'posted'], $da->constrain($user, 'bank_accounts', 'fa'), $da->constrain($user, 'bank_accounts', 'ta'));
        $rows = [];
        $total = 0;
        foreach ($this->db->select("SELECT tr.*, fa.account_code AS from_code, fa.display_name AS from_name, ta.account_code AS to_code, ta.display_name AS to_name, g.gstin
            FROM bank_transfers tr JOIN bank_accounts fa ON fa.id = tr.from_account_id JOIN bank_accounts ta ON ta.id = tr.to_account_id LEFT JOIN gst_registrations g ON g.id = tr.gst_registration_id
            WHERE {$w} ORDER BY tr.transfer_date, tr.id", $p) as $t) {
            $amount = Money::fromDb($t['amount']);
            $total += $amount;
            $rows[] = ['no' => $t['transfer_no'], 'date' => format_date($t['transfer_date']), 'from' => $t['from_code'] . ' ' . $t['from_name'], 'to' => $t['to_code'] . ' ' . $t['to_name'],
                'reference' => $t['reference_no'] ?? '—', 'purpose' => $t['purpose'], 'gstin' => $t['gstin'] ?? '', 'status' => BankTransferService::STATUSES[$t['status']], 'amount' => $amount];
        }
        return ['columns' => ['no' => ['label' => 'Transfer'], 'date' => ['label' => 'Date'], 'from' => ['label' => 'From'], 'to' => ['label' => 'To'], 'reference' => ['label' => 'Reference / UTR'],
            'purpose' => ['label' => 'Purpose'], 'gstin' => ['label' => 'GSTIN'], 'status' => ['label' => 'Status'], 'amount' => ['label' => 'Amount', 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']]],
            'rows' => $rows, 'totals' => ['no' => 'Total (' . count($rows) . ')', 'amount' => $total], 'notice' => 'Internal transfers move money between the company\'s own accounts; they are neither income nor expense.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function partnerAccounts(array $f, array $scope): array
    {
        [$w, $p] = (new BankAccountService($this->db))->filterSql(array_diff_key($f, ['partner' => 1]), $scope);
        if ((int) ($f['partner'] ?? 0) > 0) {
            $w .= ' AND m.partner_id = ?';
            $p[] = (int) $f['partner'];
        }
        if (($f['mapping'] ?? '') !== 'all') {
            $w .= " AND m.status = 'active'";
        }
        $rows = [];
        foreach ($this->db->select("SELECT m.*, pa.partner_code, pa.name AS partner_name, a.account_code, a.display_name, a.bank_name, a.account_number_last4, a.status AS account_status
            FROM bank_account_partner_mappings m JOIN partners pa ON pa.id = m.partner_id JOIN bank_accounts a ON a.id = m.bank_account_id WHERE {$w} ORDER BY pa.name, a.display_name", $p) as $m) {
            $rows[] = ['partner' => $m['partner_code'] . ' ' . $m['partner_name'], 'account' => $m['account_code'] . ' ' . $m['display_name'], 'bank' => $m['bank_name'], 'account_number' => 'XXXXXX' . $m['account_number_last4'],
                'relationship' => BankRelationService::RELATIONSHIPS[$m['relationship']], 'from' => format_date($m['effective_from']), 'to' => format_date($m['effective_to']), 'mapping' => $m['status'] === 'active' ? 'Active' : 'Ended',
                'account_status' => BankAccountService::STATUSES[$m['account_status']]];
        }
        return ['columns' => ['partner' => ['label' => 'Partner'], 'account' => ['label' => 'Account'], 'bank' => ['label' => 'Bank'], 'account_number' => ['label' => 'Account no.', 'field' => ['bank_accounts', 'account_number']],
            'relationship' => ['label' => 'Relationship'], 'from' => ['label' => 'From'], 'to' => ['label' => 'To'], 'mapping' => ['label' => 'Mapping'], 'account_status' => ['label' => 'Account status']],
            'rows' => $rows, 'totals' => ['partner' => 'Total (' . count($rows) . ')'], 'notice' => 'Associations do not imply ownership, capital share or profit share.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function gstAccounts(array $f, array $scope): array
    {
        [$w, $p] = (new BankAccountService($this->db))->filterSql(array_diff_key($f, ['gst' => 1]), $scope);
        if ((int) ($f['gst'] ?? 0) > 0) {
            $w .= ' AND m.gst_registration_id = ?';
            $p[] = (int) $f['gst'];
        }
        if (($f['mapping'] ?? '') !== 'all') {
            $w .= " AND m.status = 'active'";
        }
        $rows = [];
        foreach ($this->db->select("SELECT m.*, g.gstin, g.legal_name, s.code AS state_code, a.account_code, a.display_name, a.bank_name, a.account_number_last4
            FROM bank_account_gst_mappings m JOIN gst_registrations g ON g.id = m.gst_registration_id JOIN gst_states s ON s.id = g.state_id JOIN bank_accounts a ON a.id = m.bank_account_id
            WHERE {$w} ORDER BY g.gstin, m.designation, a.display_name", $p) as $m) {
            $rows[] = ['gstin' => $m['gstin'], 'legal_name' => $m['legal_name'], 'state' => $m['state_code'], 'account' => $m['account_code'] . ' ' . $m['display_name'], 'bank' => $m['bank_name'],
                'account_number' => 'XXXXXX' . $m['account_number_last4'], 'designation' => BankRelationService::DESIGNATIONS[$m['designation']], 'from' => format_date($m['effective_from']), 'mapping' => $m['status'] === 'active' ? 'Active' : 'Ended'];
        }
        return ['columns' => ['gstin' => ['label' => 'GSTIN', 'field' => ['gst_registrations', 'gstin']], 'legal_name' => ['label' => 'Legal name', 'field' => ['gst_registrations', 'legal_name']], 'state' => ['label' => 'State'],
            'account' => ['label' => 'Account'], 'bank' => ['label' => 'Bank'], 'account_number' => ['label' => 'Account no.', 'field' => ['bank_accounts', 'account_number']], 'designation' => ['label' => 'Designation'],
            'from' => ['label' => 'From'], 'mapping' => ['label' => 'Mapping']], 'rows' => $rows, 'totals' => ['gstin' => 'Total (' . count($rows) . ')']];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function cashFlow(array $f, array $scope): array
    {
        $ids = array_map(static fn (array $a): int => (int) $a['id'], array_filter($this->accounts($f, $scope), static fn (array $a): bool => $a['currency'] === 'INR'));
        $from = BusinessDate::isValid((string) ($f['from'] ?? '')) ? (string) $f['from'] : BusinessDate::addMonths(BusinessDate::today(), -11);
        $to = BusinessDate::isValid((string) ($f['to'] ?? '')) ? (string) $f['to'] : BusinessDate::today();
        $ledger = new BankLedgerService($this->db);
        $rows = [];
        $tot = ['received' => 0, 'paid' => 0, 'net' => 0, 'transfers' => 0, 'charges' => 0, 'interest' => 0];
        for ($m = substr($from, 0, 7) . '-01'; $m <= $to; $m = BusinessDate::addMonths($m, 1)) {
            $end = BusinessDate::addDays(BusinessDate::addMonths($m, 1), -1);
            $mv = $ledger->movement($ids, max($m, $from), min($end, $to));
            $row = ['month' => date('M Y', (int) strtotime($m)), 'received' => $mv['received'], 'paid' => $mv['paid'], 'net' => $mv['received'] - $mv['paid'], 'transfers' => $mv['transfers'], 'charges' => $mv['charges'], 'interest' => $mv['interest']];
            foreach ($tot as $k => $_) {
                $tot[$k] += $row[$k];
            }
            $rows[] = $row;
        }
        $money = static fn (string $l): array => ['label' => $l, 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']];
        return ['columns' => ['month' => ['label' => 'Month'], 'received' => $money('Received'), 'paid' => $money('Paid'), 'net' => $money('Net'), 'transfers' => $money('Internal transfers (excluded)'),
            'charges' => $money('of which charges'), 'interest' => $money('of which interest')], 'rows' => $rows, 'totals' => ['month' => 'Total'] + $tot,
            'notice' => 'Received = deposits, interest and credit adjustments; paid = withdrawals, charges and debit adjustments, net of reversals. Internal transfers and opening-balance adjustments are excluded. INR accounts only. Partner capital received is shown as money received, not as revenue.'];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function reconciliations(array $f, array $scope): array
    {
        $rs = new BankReconciliationService($this->db);
        [$w, $p] = (new BankAccountService($this->db))->filterSql(['archived' => 'with'] + $f, $scope);
        $rows = [];
        foreach ($rs->list([$w, $p], (int) ($f['account'] ?? 0) ?: null) as $r) {
            $s = $rs->summary($r);
            $rows[] = ['no' => $r['reconciliation_no'], 'account' => $r['account_code'] . ' ' . $r['account_name'], 'period' => format_date($r['period_from']) . ' – ' . format_date($r['period_to']),
                'status' => BankReconciliationService::STATUSES[$r['status']], 'matched' => $s['matched'], 'ignored' => $s['ignored'], 'unmatched' => $s['unmatched_rows'], 'outstanding' => $s['unmatched_ledger'],
                'statement' => $s['statement_closing'], 'ledger' => $r['status'] === 'completed' && $r['ledger_closing_balance'] !== null ? Money::fromDb($r['ledger_closing_balance']) : $s['ledger_closing'],
                'difference' => $s['difference'], 'by' => trim(($r['reconciled_by_name'] ?? '') . ' ' . ($r['reconciled_at'] ? format_date(substr((string) $r['reconciled_at'], 0, 10)) : '')) ?: '—'];
        }
        $money = static fn (string $l): array => ['label' => $l, 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']];
        return ['columns' => ['no' => ['label' => 'Reconciliation'], 'account' => ['label' => 'Account'], 'period' => ['label' => 'Period'], 'status' => ['label' => 'Status'], 'matched' => ['label' => 'Matched', 'type' => 'number'],
            'ignored' => ['label' => 'Ignored', 'type' => 'number'], 'unmatched' => ['label' => 'Unmatched lines', 'type' => 'number'], 'outstanding' => ['label' => 'Outstanding entries', 'type' => 'number'],
            'statement' => $money('Statement closing'), 'ledger' => $money('Ledger closing'), 'difference' => $money('Difference'), 'by' => ['label' => 'Reconciled by']], 'rows' => $rows, 'totals' => ['no' => 'Total (' . count($rows) . ')']];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function unmatched(array $f, array $scope): array
    {
        [$w, $p] = (new BankAccountService($this->db))->filterSql(['archived' => 'with'] + $f, $scope);
        foreach (['from' => 'r.txn_date >= ?', 'to' => 'r.txn_date <= ?'] as $k => $cond) {
            if (BusinessDate::isValid((string) ($f[$k] ?? ''))) {
                $w .= " AND {$cond}";
                $p[] = $f[$k];
            }
        }
        if ((int) ($f['account'] ?? 0) > 0) {
            $w .= ' AND r.bank_account_id = ?';
            $p[] = (int) $f['account'];
        }
        $rows = [];
        $dr = 0;
        $cr = 0;
        foreach ($this->db->select("SELECT r.*, a.account_code, a.display_name, s.original_name FROM bank_statement_rows r JOIN bank_statement_imports i ON i.id = r.import_id JOIN bank_statements s ON s.id = r.statement_id
            JOIN bank_accounts a ON a.id = r.bank_account_id WHERE {$w} AND i.status = 'imported' AND r.status = 'valid' AND r.match_status = 'unmatched' AND s.status = 'active' ORDER BY r.txn_date, r.id", $p) as $r) {
            $d = Money::fromDb($r['debit']);
            $c = Money::fromDb($r['credit']);
            $dr += $d;
            $cr += $c;
            $rows[] = ['date' => format_date($r['txn_date']), 'account' => $r['account_code'] . ' ' . $r['display_name'], 'description' => $r['description'] ?? '', 'reference' => $r['reference_no'] ?? '',
                'statement' => $r['original_name'] . ' · line ' . $r['row_no'], 'debit' => $d ?: null, 'credit' => $c ?: null];
        }
        $money = static fn (string $l): array => ['label' => $l, 'type' => 'money', 'field' => ['bank_accounts', 'current_balance']];
        return ['columns' => ['date' => ['label' => 'Date'], 'account' => ['label' => 'Account'], 'description' => ['label' => 'Description'], 'reference' => ['label' => 'Reference'], 'statement' => ['label' => 'Statement'],
            'debit' => $money('Debit'), 'credit' => $money('Credit')], 'rows' => $rows, 'totals' => ['date' => 'Total (' . count($rows) . ')', 'debit' => $dr, 'credit' => $cr],
            'notice' => 'Lines from imported statements that are not yet matched to a posted ledger entry or ignored. Matching happens on the Reconciliation page; nothing here changes the ledger.'];
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $out @return array<string, mixed> */
    private function applyFields(array $user, array $out): array
    {
        $fields = App::fields();
        foreach ($out['columns'] as $col => $def) {
            if (!isset($def['field'])) {
                continue;
            }
            [$fm, $ff] = $def['field'];
            $access = $fields->access($user, $fm, $ff);
            if (!$access->canView()) {
                unset($out['columns'][$col]);
                foreach ($out['rows'] as &$r) {
                    unset($r[$col]);
                }
                unset($r);
                if (is_array($out['totals'])) {
                    unset($out['totals'][$col]);
                }
                continue;
            }
            if (!$access->showsRealValue()) {
                $mask = $fields->maskType($fm, $ff);
                foreach ($out['rows'] as &$r) {
                    if (($r[$col] ?? '') !== '' && $r[$col] !== null) {
                        $r[$col] = FieldPolicy::mask(is_int($r[$col]) ? Money::toDb($r[$col]) : (string) $r[$col], $mask);
                    }
                }
                unset($r);
                if (is_array($out['totals']) && isset($out['totals'][$col])) {
                    $out['totals'][$col] = FieldPolicy::mask(is_int($out['totals'][$col]) ? Money::toDb($out['totals'][$col]) : (string) $out['totals'][$col], $mask);
                }
            }
        }
        return $out;
    }

    /** @param array<string, mixed> $f @return list<string> */
    private function describe(array $f): array
    {
        $out = [];
        if (($q = trim((string) ($f['q'] ?? ''))) !== '') {
            $out[] = 'Search: ' . $q;
        }
        if (BusinessDate::isValid((string) ($f['from'] ?? '')) || BusinessDate::isValid((string) ($f['to'] ?? ''))) {
            $out[] = 'Period: ' . (BusinessDate::isValid((string) ($f['from'] ?? '')) ? format_date($f['from']) : 'start') . ' – ' . (BusinessDate::isValid((string) ($f['to'] ?? '')) ? format_date($f['to']) : 'today');
        }
        foreach (['account' => 'SELECT account_code FROM bank_accounts WHERE id = ?', 'partner' => 'SELECT name FROM partners WHERE id = ?', 'gst' => 'SELECT gstin FROM gst_registrations WHERE id = ?',
            'type' => 'SELECT name FROM bank_account_types WHERE id = ?', 'activity' => 'SELECT name FROM gst_business_activities WHERE id = ?'] as $k => $sql) {
            if ((int) ($f[$k] ?? 0) > 0) {
                $out[] = ucfirst($k) . ': ' . (string) $this->db->scalar($sql, [(int) $f[$k]]);
            }
        }
        if (($f['bank'] ?? '') !== '') {
            $out[] = 'Bank: ' . $f['bank'];
        }
        return $out;
    }
