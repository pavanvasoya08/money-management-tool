<?php

declare(strict_types=1);

namespace App\Services\Gst;

use App\Core\App;
use App\Core\Database;
use App\Exceptions\HttpException;
use App\Services\Authorization\FieldPolicy;
use App\Support\BusinessDate;

/**
 * GST registration reports. Every report is restricted in SQL to the records the
 * user may see (gst_registrations record scope) and passes through the field
 * rules (hidden columns are removed, masked values masked) — identically on
 * screen and in CSV / Excel / PDF exports.
 */
final class GstReportService
{
    /** key => [title, description] */
    public const REPORTS = [
        'all' => ['All GST registrations', 'Every registration with type, state, status and dates.'],
        'active' => ['Active GST registrations', 'Registrations currently active.'],
        'state_wise' => ['State-wise registrations', 'Number of registrations per state or union territory, by status.'],
        'partner_wise' => ['Partner-wise registrations', 'Each partner with the registrations mapped to them and the relationship.'],
        'type_summary' => ['Registration type-wise summary', 'Number of registrations per registration type, by status.'],
        'cancelled_suspended' => ['Cancelled and suspended registrations', 'With the cancellation date and reason.'],
        'recently_updated' => ['Recently updated registrations', 'Changed in the chosen period (default: last 30 days).'],
    ];

    public function __construct(private readonly Database $db)
    {
    }

    /**
     * @param array<string, mixed> $user @param array<string, mixed> $filters
     * @return array{title: string, columns: array<string, array<string, mixed>>, rows: list<array<string, mixed>>, totals: ?array<string, mixed>, meta: list<string>, notice: ?string}
     */
    public function run(array $user, string $key, array $filters): array
    {
        if (!isset(self::REPORTS[$key])) {
            throw new HttpException(404, 'Report not found.');
        }
        $scope = App::dataAccess()->constrain($user, 'gst_registrations', 'g');
        $out = match ($key) {
            'all' => $this->list($filters, $scope),
            'active' => $this->list(['status' => 'active'] + $filters, $scope),
            'cancelled_suspended' => $this->list(['status' => 'cancelled_suspended'] + $filters, $scope, withCancellation: true),
            'recently_updated' => $this->recent($filters, $scope),
            'state_wise' => $this->grouped($filters, $scope, 'state'),
            'type_summary' => $this->grouped($filters, $scope, 'type'),
            'partner_wise' => $this->partnerWise($user, $filters, $scope),
        };
        $out += ['totals' => null, 'notice' => null];
        $out = $this->applyFields($user, $out);
        $out['title'] = self::REPORTS[$key][0];
        $out['meta'] = array_merge([App::dataAccess()->resolve($user, 'gst_registrations')->describe() . ' · generated by ' . $user['name'] . ' · ' . format_datetime(now())], $this->describe($filters));
        return $out;
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function list(array $f, array $scope, bool $withCancellation = false): array
    {
        [$w, $p] = (new GstRegistrationService($this->db))->filterSql($f, $scope);
        $rows = $this->db->select(
            "SELECT g.*, s.code AS state_code, s.name AS state_name, t.name AS type_name,
                    (SELECT COUNT(*) FROM gst_registration_partner_mappings m WHERE m.gst_registration_id = g.id AND m.status = 'active') AS partners
             FROM gst_registrations g JOIN gst_states s ON s.id = g.state_id JOIN gst_registration_types t ON t.id = g.registration_type_id
             WHERE {$w} ORDER BY " . GstRegistrationService::orderBy((string) ($f['sort'] ?? 'legal_name')),
            $p
        );
        $columns = [
            'gstin' => ['label' => 'GSTIN', 'field' => ['gst_registrations', 'gstin']],
            'legal_name' => ['label' => 'Legal name', 'field' => ['gst_registrations', 'legal_name']],
            'trade_name' => ['label' => 'Trade name', 'field' => ['gst_registrations', 'trade_name']],
            'state' => ['label' => 'State'],
            'type' => ['label' => 'Type'],
            'status' => ['label' => 'Status'],
            'registration_date' => ['label' => 'Registration date'],
            'effective_from' => ['label' => 'Effective from'],
            'partners' => ['label' => 'Partners', 'type' => 'number'],
        ];
        if ($withCancellation) {
            $columns += ['cancellation_date' => ['label' => 'Cancellation date'], 'status_reason' => ['label' => 'Reason']];
        }
        $out = [];
        foreach ($rows as $r) {
            $out[] = [
                'id' => (int) $r['id'], 'gstin' => $r['gstin'], 'legal_name' => $r['legal_name'], 'trade_name' => $r['trade_name'] ?? '',
                'state' => $r['state_code'] . ' · ' . $r['state_name'], 'type' => $r['type_name'],
                'status' => GstRegistrationService::STATUSES[$r['status']] . ((int) $r['is_archived'] ? ' (archived)' : ''),
                'registration_date' => format_date($r['registration_date']), 'effective_from' => format_date($r['effective_from']), 'partners' => (int) $r['partners'],
                'cancellation_date' => format_date($r['cancellation_date']), 'status_reason' => (string) ($r['status_reason'] ?? ''),
            ];
        }
        return ['columns' => $columns, 'rows' => $out, 'totals' => ['gstin' => 'Total (' . count($out) . ')']];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function recent(array $f, array $scope): array
    {
        $from = BusinessDate::isValid((string) ($f['from'] ?? '')) ? (string) $f['from'] : BusinessDate::addDays(BusinessDate::today(), -30);
        $to = BusinessDate::isValid((string) ($f['to'] ?? '')) ? (string) $f['to'] : BusinessDate::today();
        // from/to apply to the update time here, not to the registration date.
        $g = ['from' => '', 'to' => ''] + $f;
        $g['from'] = '';
        $g['to'] = '';
        [$w, $p] = (new GstRegistrationService($this->db))->filterSql($g, $scope);
        $rows = $this->db->select(
            "SELECT g.*, s.code AS state_code, t.name AS type_name, u.name AS updated_by_name
             FROM gst_registrations g JOIN gst_states s ON s.id = g.state_id JOIN gst_registration_types t ON t.id = g.registration_type_id LEFT JOIN users u ON u.id = g.updated_by
             WHERE {$w} AND g.updated_at >= ? AND g.updated_at < ? ORDER BY g.updated_at DESC, g.id DESC",
            array_merge($p, [$from . ' 00:00:00', BusinessDate::addDays($to, 1) . ' 00:00:00'])
        );
        $out = [];
        foreach ($rows as $r) {
            $out[] = ['id' => (int) $r['id'], 'gstin' => $r['gstin'], 'legal_name' => $r['legal_name'], 'state' => $r['state_code'], 'type' => $r['type_name'],
                'status' => GstRegistrationService::STATUSES[$r['status']], 'updated_at' => format_datetime($r['updated_at']), 'updated_by' => (string) ($r['updated_by_name'] ?? '—')];
        }
        return [
            'columns' => ['gstin' => ['label' => 'GSTIN', 'field' => ['gst_registrations', 'gstin']], 'legal_name' => ['label' => 'Legal name', 'field' => ['gst_registrations', 'legal_name']],
                'state' => ['label' => 'State'], 'type' => ['label' => 'Type'], 'status' => ['label' => 'Status'], 'updated_at' => ['label' => 'Last updated'], 'updated_by' => ['label' => 'Updated by']],
            'rows' => $out, 'totals' => ['gstin' => 'Total (' . count($out) . ')'],
            'notice' => 'Period: ' . format_date($from) . ' – ' . format_date($to) . '. Every individual change is listed in each registration\'s History tab.',
        ];
    }

    /** @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function grouped(array $f, array $scope, string $by): array
    {
        [$w, $p] = (new GstRegistrationService($this->db))->filterSql($f, $scope);
        [$select, $join, $group, $label] = $by === 'state'
            ? ["s.code AS k, s.name AS name", 'JOIN gst_states s ON s.id = g.state_id', 's.code, s.name', 'State / UT']
            : ['t.code AS k, t.name AS name', 'JOIN gst_registration_types t ON t.id = g.registration_type_id', 't.code, t.name, t.sort_order', 'Registration type'];
        $statusCols = '';
        foreach (array_keys(GstRegistrationService::STATUSES) as $st) {
            $statusCols .= ", SUM(CASE WHEN g.status = '{$st}' THEN 1 ELSE 0 END) AS st_{$st}";
        }
        $rows = $this->db->select("SELECT {$select}, COUNT(*) AS total{$statusCols} FROM gst_registrations g {$join} WHERE {$w} GROUP BY {$group} ORDER BY total DESC, name", $p);
        $columns = ['group' => ['label' => $label]];
        foreach (GstRegistrationService::STATUSES as $st => $l) {
            $columns['st_' . $st] = ['label' => $l, 'type' => 'number'];
        }
        $columns['total'] = ['label' => 'Total', 'type' => 'number'];
        $totals = ['group' => 'Total'];
        $out = [];
        foreach ($rows as $r) {
            $row = ['group' => ($by === 'state' ? $r['k'] . ' · ' : '') . $r['name'], 'total' => (int) $r['total']];
            foreach (array_keys(GstRegistrationService::STATUSES) as $st) {
                $row['st_' . $st] = (int) $r['st_' . $st];
                $totals['st_' . $st] = ($totals['st_' . $st] ?? 0) + (int) $r['st_' . $st];
            }
            $totals['total'] = ($totals['total'] ?? 0) + (int) $r['total'];
            $out[] = $row;
        }
        return ['columns' => $columns, 'rows' => $out, 'totals' => $out === [] ? null : $totals];
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $f @param array{0: string, 1: list<mixed>} $scope @return array<string, mixed> */
    private function partnerWise(array $user, array $f, array $scope): array
    {
        [$w, $p] = (new GstRegistrationService($this->db))->filterSql(['partner' => 0] + $f, $scope);
        $extra = '';
        if ((int) ($f['partner'] ?? 0) > 0) {
            $extra = ' AND m.partner_id = ?';
            $p[] = (int) $f['partner'];
        }
        $active = ($f['mapping'] ?? '') === 'all' ? '' : " AND m.status = 'active'";
        // Partners the user may not see are named only by code in this report.
        [$pw, $pp] = App::dataAccess()->constrain($user, 'partners', 'pa');
        $rows = $this->db->select(
            "SELECT m.effective_from, m.effective_to, m.status AS mapping_status, pa.partner_code, pa.name AS partner_name, CASE WHEN {$pw} THEN 1 ELSE 0 END AS partner_visible, g.gstin, g.legal_name, g.status AS registration_status, s.code AS state_code, r.name AS relationship
             FROM gst_registration_partner_mappings m JOIN partners pa ON pa.id = m.partner_id JOIN gst_registrations g ON g.id = m.gst_registration_id
             JOIN gst_states s ON s.id = g.state_id JOIN gst_partner_relationship_types r ON r.id = m.relationship_type_id
             WHERE {$w}{$active}{$extra} ORDER BY pa.name, g.legal_name",
            array_merge($pp, $p)
        );
        $out = [];
        foreach ($rows as $r) {
            $out[] = ['partner' => (int) $r['partner_visible'] ? $r['partner_code'] . ' · ' . $r['partner_name'] : $r['partner_code'], 'gstin' => $r['gstin'], 'legal_name' => $r['legal_name'],
                'state' => $r['state_code'], 'relationship' => $r['relationship'], 'effective_from' => format_date($r['effective_from']), 'effective_to' => format_date($r['effective_to']),
                'mapping' => $r['mapping_status'] === 'active' ? 'Active' : 'Ended', 'status' => GstRegistrationService::STATUSES[$r['registration_status']]];
        }
        return [
            'columns' => ['partner' => ['label' => 'Partner'], 'gstin' => ['label' => 'GSTIN', 'field' => ['gst_registrations', 'gstin']], 'legal_name' => ['label' => 'Legal name', 'field' => ['gst_registrations', 'legal_name']],
                'state' => ['label' => 'State'], 'relationship' => ['label' => 'Relationship'], 'effective_from' => ['label' => 'From'], 'effective_to' => ['label' => 'To'],
                'mapping' => ['label' => 'Mapping'], 'status' => ['label' => 'Registration status']],
            'rows' => $out, 'totals' => ['partner' => 'Total (' . count($out) . ' mappings)'],
            'notice' => 'A mapping records a relationship only. It does not imply ownership shares, capital or profit-sharing percentages.',
        ];
    }

    /** @param array<string, mixed> $user @param array<string, mixed> $out @return array<string, mixed> */
    private function applyFields(array $user, array $out): array
    {
        $fields = App::fields();
        foreach ($out['columns'] as $col => $def) {
            if (!isset($def['field'])) {
                continue;
            }
            [$fm, $ff] = $def['field'];
            $access = $fields->access($user, $fm, $ff);
            if (!$access->canView()) {
                unset($out['columns'][$col]);
                foreach ($out['rows'] as &$r) {
                    unset($r[$col]);
                }
                unset($r);
                if (is_array($out['totals']) && array_key_first($out['totals']) === $col) {
                    $label = $out['totals'][$col];
                    unset($out['totals'][$col]);
                    $first = array_key_first($out['columns']);
                    if ($first !== null) {
                        $out['totals'] = [$first => $label] + $out['totals'];
                    }
                }
                continue;
            }
            if (!$access->showsRealValue()) {
                $mask = $fields->maskType($fm, $ff);
                foreach ($out['rows'] as &$r) {
                    if (($r[$col] ?? '') !== '') {
                        $r[$col] = FieldPolicy::mask((string) $r[$col], $mask);
                    }
                }
                unset($r);
            }
        }
        return $out;
    }

    /** @param array<string, mixed> $f @return list<string> */
    private function describe(array $f): array
    {
        $out = [];
        if (($q = trim((string) ($f['q'] ?? ''))) !== '') {
            $out[] = 'Search: ' . $q;
        }
        if ((int) ($f['state'] ?? 0) > 0) {
            $st = $this->db->first('SELECT code, name FROM gst_states WHERE id = ?', [(int) $f['state']]);
            $out[] = 'State: ' . ($st !== null ? $st['code'] . ' · ' . $st['name'] : '—');
        }
        if ((int) ($f['type'] ?? 0) > 0) {
            $out[] = 'Type: ' . (string) $this->db->scalar('SELECT name FROM gst_registration_types WHERE id = ?', [(int) $f['type']]);
        }
        if (isset(GstRegistrationService::STATUSES[(string) ($f['status'] ?? '')])) {
            $out[] = 'Status: ' . GstRegistrationService::STATUSES[$f['status']];
        }
        if ((int) ($f['partner'] ?? 0) > 0) {
            $out[] = 'Partner: ' . (string) $this->db->scalar('SELECT partner_code FROM partners WHERE id = ?', [(int) $f['partner']]);
        }
        foreach (['from' => 'From', 'to' => 'To'] as $k => $l) {
            if (BusinessDate::isValid((string) ($f[$k] ?? ''))) {
                $out[] = "{$l}: " . format_date((string) $f[$k]);
            }
        }
        return $out;
    }
}
